"""Contrats (DIP) : le domaine/application dépendent de ces Protocols, jamais des implémentations."""
from typing import Protocol

from .models import Anonymized, Entity, RiskRow, SupplyAlert


class MappingStore(Protocol):
    def original(self, alias: str) -> str | None: ...
    def put(self, alias: str, kind: str, original: str) -> None: ...
    def all(self) -> list[dict]: ...


class EntityCatalog(Protocol):
    def entities(self) -> list[Entity]: ...


class Anonymizer(Protocol):
    engine: str
    def anonymize(self, text: str) -> Anonymized: ...
    def restore(self, text: str) -> str: ...


class LLMClient(Protocol):
    def complete(self, system: str, user: str) -> str: ...


class TerritoryRepository(Protocol):
    def available(self) -> bool: ...
    def query(self, name: str, region: str = "ALL") -> list[dict]: ...
    def pair(self, x: str, y: str) -> list[dict]: ...
    def lineage(self) -> dict: ...


class ProjetsRepository(Protocol):
    def available(self) -> bool: ...
    def query(self, name: str) -> list[dict]: ...
    def backtests(self) -> list[dict]: ...
    def sql(self) -> dict[str, dict]: ...


class FleetRepository(Protocol):
    def risk_ranking(self) -> list[RiskRow]: ...
    def supply_alerts(self) -> list[SupplyAlert]: ...
    def latest_report(self, asset_id: int) -> str | None: ...


class FrancophonieRepository(Protocol):
    def available(self) -> bool: ...
    def query(self, name: str) -> list[dict]: ...
    def sql(self) -> dict[str, dict]: ...
    def sources(self) -> list[dict]: ...
